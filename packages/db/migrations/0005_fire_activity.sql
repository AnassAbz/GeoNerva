-- 0005 — fire activity: detections, clusters and the long-term aggregate
-- (DOMAIN_MODEL §4.9, §4.10, §6.4, ADR-009, ADR-011, ADR-018).
--
-- `fire_detections` is the only high-volume table (P0 measured ≈73k rows/day/satellite for
-- NOAA-20 + NOAA-21, i.e. ≈146k/day). It is therefore partitioned by day, and retention is a
-- `DROP TABLE` of whole partitions rather than a delete — which is the difference between a
-- 72-hour replay horizon that works on a 500 MB database and one that does not.
--
-- Detections are immutable and have no revisions. A NRT row is never updated in place by a
-- standard-processing row: SP would be a separate product, and therefore separate rows.

CREATE TABLE geonerva.fire_detections (
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  product_id        smallint NOT NULL REFERENCES geonerva.source_products (id),
  acquired_at       timestamptz NOT NULL,
  lat               double precision NOT NULL CHECK (lat >= -90 AND lat <= 90),
  lon               double precision NOT NULL CHECK (lon >= -180 AND lon < 180),
  -- Rounded coordinates form the idempotency key: FIRMS has no stable detection id, and a pixel
  -- centre repeats to about 1e-4° (≈ 11 m) across polls (DATA_SOURCES §3.4).
  lat_e4            integer GENERATED ALWAYS AS (round(lat * 1e4)::integer) STORED,
  lon_e4            integer GENERATED ALWAYS AS (round(lon * 1e4)::integer) STORED,
  geog              geography(Point, 4326) NOT NULL,
  -- Normalized to LOW/NOMINAL/HIGH for VIIRS; the provider's own value is kept verbatim.
  confidence_class  text CHECK (confidence_class IN ('LOW', 'NOMINAL', 'HIGH')),
  confidence_raw    text,
  frp               real CHECK (frp IS NULL OR frp >= 0),
  bright_ti4        real,
  bright_ti5        real,
  -- Along-scan and along-track pixel size in km: a 375 m pixel grows to ~0.8 km off-nadir, which
  -- is why the clustering epsilon is 1.5 km (ARCHITECTURE §7.4).
  scan              real,
  track             real,
  daynight          char(1) CHECK (daynight IS NULL OR daynight IN ('D', 'N')),
  -- e.g. '2.0NRT'. A future URT/RT row would be distinguishable here (V4).
  provider_version  text,
  ingestion_run_id  uuid REFERENCES geonerva.ingestion_runs (id),
  ingested_at       timestamptz NOT NULL,
  cluster_id        uuid,
  PRIMARY KEY (acquired_at, id),
  UNIQUE (product_id, acquired_at, lat_e4, lon_e4),
  CHECK (acquired_at <= ingested_at + interval '5 minutes')
) PARTITION BY RANGE (acquired_at);

COMMENT ON TABLE geonerva.fire_detections IS
  'Immutable satellite thermal detections. A detection is the centre of a pixel flagged as
   containing one or more fires — not a perimeter, not a fire count, not a confirmed wildfire.';
COMMENT ON COLUMN geonerva.fire_detections.cluster_id IS
  'Assigned once. A detection never changes cluster except through a cluster merge, which is
   recorded on the cluster rather than by rewriting detections.';

-- Indexes declared on the partitioned parent are created on every partition automatically.
CREATE INDEX fire_detections_geog_gix ON geonerva.fire_detections USING gist (geog);
CREATE INDEX fire_detections_cluster_idx ON geonerva.fire_detections (cluster_id)
  WHERE cluster_id IS NOT NULL;
CREATE INDEX fire_detections_ingested_brin_idx
  ON geonerva.fire_detections USING brin (ingested_at);

-- Partition maintenance. The worker calls these nightly; the migration creates a window around
-- the deployment date so that the first ingestion run has somewhere to write.
CREATE FUNCTION geonerva.ensure_fire_detection_partition(day date)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  partition_name text := format('fire_detections_%s', to_char(day, 'YYYYMMDD'));
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'geonerva' AND c.relname = partition_name
  ) THEN
    EXECUTE format(
      'CREATE TABLE geonerva.%I PARTITION OF geonerva.fire_detections FOR VALUES FROM (%L) TO (%L)',
      partition_name, day::timestamptz, (day + 1)::timestamptz);
  END IF;
  RETURN partition_name;
END
$$;

COMMENT ON FUNCTION geonerva.ensure_fire_detection_partition(date) IS
  'Idempotently creates the daily partition for `day`. Safe to call from every ingestion run.';

CREATE FUNCTION geonerva.ensure_fire_detection_partitions(from_day date, days integer)
RETURNS SETOF text
LANGUAGE plpgsql
AS $$
DECLARE
  offset_days integer;
BEGIN
  IF days <= 0 OR days > 4000 THEN
    RAISE EXCEPTION 'days must be between 1 and 4000 (got %)', days;
  END IF;
  FOR offset_days IN 0 .. days - 1 LOOP
    RETURN NEXT geonerva.ensure_fire_detection_partition(from_day + offset_days);
  END LOOP;
END
$$;

CREATE FUNCTION geonerva.drop_fire_detection_partitions_before(cutoff date)
RETURNS SETOF text
LANGUAGE plpgsql
AS $$
DECLARE
  partition record;
BEGIN
  FOR partition IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_inherits i ON i.inhrelid = c.oid
    JOIN pg_class parent ON parent.oid = i.inhparent
    JOIN pg_namespace pn ON pn.oid = parent.relnamespace
    WHERE pn.nspname = 'geonerva'
      AND parent.relname = 'fire_detections'
      AND n.nspname = 'geonerva'
      AND c.relname ~ '^fire_detections_[0-9]{8}$'
      AND to_date(right(c.relname, 8), 'YYYYMMDD') < cutoff
    ORDER BY c.relname
  LOOP
    EXECUTE format('DROP TABLE geonerva.%I', partition.relname);
    RETURN NEXT partition.relname;
  END LOOP;
END
$$;

COMMENT ON FUNCTION geonerva.drop_fire_detection_partitions_before(date) IS
  'Retention for thermal detections: whole partitions are dropped, never rows deleted (ADR-018).
   Returns the names dropped, which the retention analysis_run records.';

-- A window around the deployment date, so a fresh database can ingest immediately.
SELECT geonerva.ensure_fire_detection_partitions((CURRENT_DATE - 3)::date, 8);

CREATE TABLE geonerva.fire_clusters (
  id                uuid PRIMARY KEY,
  public_id         text NOT NULL UNIQUE,
  created_at        timestamptz NOT NULL,
  status            text NOT NULL CHECK (status IN ('ACTIVE', 'COOLING', 'INACTIVE', 'MERGED')),
  merged_into       uuid REFERENCES geonerva.fire_clusters (id),
  merged_at         timestamptz,
  -- P1: a heat source that is present in every overpass for weeks (gas flare, industrial site).
  -- Such a cluster is capped at LOW relevance rather than reported as fire activity.
  persistent_source boolean NOT NULL DEFAULT false,
  CHECK ((merged_into IS NULL) = (merged_at IS NULL)),
  CHECK (merged_into IS NULL OR merged_into <> id)
);

COMMENT ON TABLE geonerva.fire_clusters IS
  'A group of detections treated as one area of thermal activity. Never called a wildfire.
   Clusters merge (older survives) but never split in v1 (documented simplification, §4.10).';

CREATE INDEX fire_clusters_status_idx ON geonerva.fire_clusters (status);
CREATE INDEX fire_clusters_merged_into_idx
  ON geonerva.fire_clusters (merged_into) WHERE merged_into IS NOT NULL;

ALTER TABLE geonerva.fire_detections
  ADD CONSTRAINT fire_detections_cluster_fkey
  FOREIGN KEY (cluster_id) REFERENCES geonerva.fire_clusters (id);

CREATE TABLE geonerva.fire_cluster_versions (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cluster_id         uuid NOT NULL REFERENCES geonerva.fire_clusters (id),
  analysis_run_id    uuid,
  -- The knowledge time this summary was computed for. This is what replay filters on: cluster
  -- versions have no ingested_at because they are derived, not ingested (DOMAIN_MODEL §2).
  as_of              timestamptz NOT NULL,
  computed_at        timestamptz NOT NULL DEFAULT now(),
  n_total            integer NOT NULL CHECK (n_total >= 0),
  n_24h              integer NOT NULL CHECK (n_24h >= 0),
  -- Distinct (product, acquired_at within 10 min) groups: two overpasses are two independent
  -- looks, which is why relevance uses this and not the raw count.
  overpasses_24h     integer NOT NULL CHECK (overpasses_24h >= 0),
  first_detected_at  timestamptz NOT NULL,
  last_detected_at   timestamptz NOT NULL,
  frp_sum_24h        real CHECK (frp_sum_24h IS NULL OR frp_sum_24h >= 0),
  frp_max            real CHECK (frp_max IS NULL OR frp_max >= 0),
  max_confidence     text CHECK (max_confidence IS NULL OR max_confidence IN ('LOW', 'NOMINAL', 'HIGH')),
  product_ids        smallint[] NOT NULL DEFAULT '{}',
  -- Convex hull of the members, buffered by half a pixel. Not a fire perimeter.
  hull               geography(Polygon, 4326),
  centroid           geography(Point, 4326) NOT NULL,
  content_sha256     bytea NOT NULL CHECK (octet_length(content_sha256) = 32),
  CHECK (n_24h <= n_total),
  CHECK (last_detected_at >= first_detected_at),
  -- Idempotency: a clustering re-run for the same as_of with an unchanged summary writes nothing.
  UNIQUE (cluster_id, content_sha256)
);

COMMENT ON TABLE geonerva.fire_cluster_versions IS
  'Immutable cluster summaries. A new row exists only where the summary hash changed.';

CREATE INDEX fire_cluster_versions_hull_gix
  ON geonerva.fire_cluster_versions USING gist (hull);
CREATE INDEX fire_cluster_versions_centroid_gix
  ON geonerva.fire_cluster_versions USING gist (centroid);
CREATE INDEX fire_cluster_versions_cluster_asof_idx
  ON geonerva.fire_cluster_versions (cluster_id, as_of DESC, id DESC);
CREATE INDEX fire_cluster_versions_asof_brin_idx
  ON geonerva.fire_cluster_versions USING brin (as_of);

CREATE TABLE geonerva.fire_cluster_heads (
  cluster_id         uuid PRIMARY KEY REFERENCES geonerva.fire_clusters (id),
  latest_version_id  bigint NOT NULL REFERENCES geonerva.fire_cluster_versions (id),
  status             text NOT NULL,
  as_of              timestamptz NOT NULL,
  last_detected_at   timestamptz NOT NULL
);

COMMENT ON TABLE geonerva.fire_cluster_heads IS
  'Cache of the latest cluster version, for the now fast path. Rebuildable from versions.';

CREATE INDEX fire_cluster_heads_status_idx ON geonerva.fire_cluster_heads (status);

CREATE TABLE geonerva.fire_daily_cells (
  -- Regular lat/lon grid index rather than H3: baselines compare a place with its own history, so
  -- equal-area cells buy nothing and would add a dependency and approximation error (ADR-011).
  cell_id        integer NOT NULL,
  day            date NOT NULL,
  product_group  text NOT NULL,
  n              integer NOT NULL CHECK (n >= 0),
  frp_sum        real,
  n_high_conf    integer NOT NULL DEFAULT 0 CHECK (n_high_conf >= 0),
  PRIMARY KEY (cell_id, day, product_group),
  CHECK (n_high_conf <= n)
);

COMMENT ON TABLE geonerva.fire_daily_cells IS
  'Compact long-term aggregate for fire trends, surviving detection retention (0.25°, lean 0.5°).';

CREATE INDEX fire_daily_cells_day_idx ON geonerva.fire_daily_cells (day);

-- Days on which FIRMS reported no satellite data, so that "no detections" and "no coverage" are
-- never confused in a trend (ARCHITECTURE §8.2).
CREATE TABLE geonerva.fire_missing_data_days (
  product_id  smallint NOT NULL REFERENCES geonerva.source_products (id),
  day         date NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (product_id, day)
);

COMMENT ON TABLE geonerva.fire_missing_data_days IS
  'FIRMS `missing_data`: days with no satellite coverage. Excluded from per-day normalization.';
