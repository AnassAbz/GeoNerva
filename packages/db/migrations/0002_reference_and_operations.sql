-- 0002 — reference data (sources, products) and ingestion operations (runs, rejects).
--
-- `ingestion_runs` is the single source of truth for source health: health is **derived** from
-- committed runs plus the freshness policy, never stored (ADR-022, DOMAIN_MODEL §4.3). Failed
-- runs are committed too, with zero versions, because failure is the evidence.

CREATE TABLE geonerva.sources (
  id                text PRIMARY KEY
                      CHECK (id ~ '^[a-z][a-z0-9_-]{1,31}$'),
  name              text NOT NULL,
  homepage          text,
  licence           text NOT NULL,
  attribution_text  text NOT NULL,
  terms_url         text,
  disclaimer        text,
  -- NULL means global coverage. A polygon means "this source only covers this area", which the
  -- UI turns into an explicit "not covered here" rather than into silence.
  coverage          geography(MultiPolygon, 4326),
  coverage_note     text,
  enabled           boolean NOT NULL DEFAULT true,
  -- { freshness: FreshnessPolicy, polling: PollingPolicy } — see packages/domain.
  policy            jsonb NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE geonerva.sources IS
  'One provider. Code branches on capabilities, never on these ids (ARCHITECTURE §3 rule 4).';
COMMENT ON COLUMN geonerva.sources.coverage IS 'NULL = global coverage.';
COMMENT ON COLUMN geonerva.sources.policy IS
  'SourcePolicy JSON: { freshness: FreshnessPolicy, polling: PollingPolicy }.';

CREATE TABLE geonerva.source_products (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id         text NOT NULL REFERENCES geonerva.sources (id),
  code              text NOT NULL,
  hazard_types      text[] NOT NULL,
  capabilities      text[] NOT NULL,
  -- Sensor lifecycle, so that retiring a satellite is a data change, not a code change (ADR-009).
  platform          text,
  instrument        text,
  resolution_m      integer CHECK (resolution_m IS NULL OR resolution_m > 0),
  confidence_scale  text CHECK (confidence_scale IN ('CATEGORICAL', 'NUMERIC')),
  latency_class     text CHECK (latency_class IN ('URT', 'RT', 'NRT', 'STANDARD', 'MINUTES', 'HOURS')),
  status            text NOT NULL CHECK (status IN ('ACTIVE', 'RETIRING', 'RETIRED')),
  active_from       date,
  active_to         date,
  enabled           boolean NOT NULL DEFAULT true,
  policy            jsonb,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, code),
  CHECK (active_to IS NULL OR active_from IS NULL OR active_to >= active_from),
  CHECK (cardinality(hazard_types) > 0)
);

COMMENT ON TABLE geonerva.source_products IS
  'A feed or sensor within a source, with its lifecycle. Adding or retiring one is a data change.';

CREATE TABLE geonerva.ingestion_runs (
  id                  uuid PRIMARY KEY,
  source_id           text NOT NULL REFERENCES geonerva.sources (id),
  product_id          smallint REFERENCES geonerva.source_products (id),
  trigger             text NOT NULL CHECK (trigger IN ('SCHEDULE', 'MANUAL', 'BACKFILL', 'RECONCILE')),
  started_at          timestamptz NOT NULL,
  finished_at         timestamptz,
  -- The batch timestamp, taken with clock_timestamp() immediately before COMMIT. This is the
  -- `ingested_at` of every version in the batch, and the only thing replay looks at.
  committed_at        timestamptz,
  status              text NOT NULL
                        CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED', 'SKIPPED')),
  http_status         integer,
  bytes_received      bigint CHECK (bytes_received IS NULL OR bytes_received >= 0),
  payload_sha256      bytea CHECK (payload_sha256 IS NULL OR octet_length(payload_sha256) = 32),
  n_received          integer NOT NULL DEFAULT 0 CHECK (n_received >= 0),
  n_new_records       integer NOT NULL DEFAULT 0 CHECK (n_new_records >= 0),
  n_new_versions      integer NOT NULL DEFAULT 0 CHECK (n_new_versions >= 0),
  n_unchanged         integer NOT NULL DEFAULT 0 CHECK (n_unchanged >= 0),
  n_rejected          integer NOT NULL DEFAULT 0 CHECK (n_rejected >= 0),
  newest_observed_at  timestamptz,
  error_class         text CHECK (error_class IN (
                        'HTTP_4XX', 'HTTP_5XX', 'TIMEOUT', 'TOO_LARGE', 'SCHEMA_DRIFT',
                        'EMPTY_SUSPICIOUS', 'RATE_LIMITED', 'DB_ERROR', 'LEASE_EXPIRED', 'UNKNOWN')),
  -- Sanitized and bounded: never a provider body, a stack trace or a connection string.
  error_message       text CHECK (error_message IS NULL OR octet_length(error_message) <= 1024),
  worker_version      text,
  CHECK (finished_at IS NULL OR finished_at >= started_at),
  CHECK (committed_at IS NULL OR committed_at >= started_at),
  -- A run is knowledge only once it has committed; a terminal run must therefore have a
  -- committed_at, and a RUNNING run must not.
  CHECK ((status = 'RUNNING') = (committed_at IS NULL))
);

COMMENT ON TABLE geonerva.ingestion_runs IS
  'One adapter execution for one product. The only input to the source-health derivation.';
COMMENT ON COLUMN geonerva.ingestion_runs.committed_at IS
  'Batch timestamp taken immediately before COMMIT; equals ingested_at of the batch''s versions.';

-- Health at an arbitrary knowledge time: "every run committed at or before T, newest first".
CREATE INDEX ingestion_runs_source_committed_idx
  ON geonerva.ingestion_runs (source_id, committed_at DESC);
CREATE INDEX ingestion_runs_product_started_idx
  ON geonerva.ingestion_runs (source_id, product_id, started_at DESC);

-- The run lease: at most one RUNNING run per product, which makes overlapping polls impossible
-- (DOMAIN_MODEL §6.6). COALESCE is needed because a NULL product_id would otherwise never
-- collide with itself, and source-level runs must be serialized too.
CREATE UNIQUE INDEX ingestion_runs_lease_idx
  ON geonerva.ingestion_runs (source_id, COALESCE(product_id, -1))
  WHERE status = 'RUNNING';

CREATE TABLE geonerva.ingestion_rejects (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       uuid NOT NULL REFERENCES geonerva.ingestion_runs (id) ON DELETE CASCADE,
  reason_code  text NOT NULL,
  -- A bounded excerpt of the offending record, for debugging schema drift. Never the whole body.
  excerpt      jsonb,
  created_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE geonerva.ingestion_rejects IS
  'Records refused at parse or normalize time. Retention: 30 days.';

CREATE INDEX ingestion_rejects_run_idx ON geonerva.ingestion_rejects (run_id);
CREATE INDEX ingestion_rejects_created_brin_idx
  ON geonerva.ingestion_rejects USING brin (created_at);

-- The worker heartbeat shown on /data-status ("worker last seen"). One row, updated every minute.
CREATE TABLE geonerva.worker_heartbeat (
  id           boolean PRIMARY KEY DEFAULT true CHECK (id),
  last_seen_at timestamptz NOT NULL,
  version      text
);

COMMENT ON TABLE geonerva.worker_heartbeat IS
  'Single-row liveness marker for the ingestion worker (ARCHITECTURE §14).';
