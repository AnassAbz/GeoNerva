-- 0003 — provider facts: the append-only, bitemporal core (ADR-003, DOMAIN_MODEL §4.5–§4.7).
--
-- Identity is separate from content. A `source_record` is "one thing a provider talks about" and
-- never changes; an `observation_version` is one immutable statement about it. Nothing here is
-- ever updated in place, except `source_record_heads`, which is a cache of "the latest version"
-- maintained in the same transaction as the insert.
--
-- Version creation is decided **only** by comparing `content_sha256` of the normalized content
-- with the record's latest version. It is never decided by a provider's "last modified" field:
-- GDACS bulk-restamps `datemodified` on dozens of unrelated old events within the same minute, so
-- that field is not a change signal (P0 verification).

CREATE TABLE geonerva.raw_source_records (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id       text NOT NULL REFERENCES geonerva.sources (id),
  payload_sha256  bytea NOT NULL CHECK (octet_length(payload_sha256) = 32),
  -- NULL after the retention window prunes the body. The hash stays forever, so an audit can
  -- still prove what was ingested even when the payload itself is gone (DOMAIN_MODEL §4.5).
  payload         jsonb,
  payload_pruned  boolean NOT NULL DEFAULT false,
  first_seen_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, payload_sha256)
);

COMMENT ON TABLE geonerva.raw_source_records IS
  'Content-addressed provider payloads for event-scale sources. Not used for FIRMS.';

CREATE INDEX raw_source_records_first_seen_brin_idx
  ON geonerva.raw_source_records USING brin (first_seen_at);

CREATE TABLE geonerva.source_records (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id          text NOT NULL REFERENCES geonerva.sources (id),
  product_id         smallint REFERENCES geonerva.source_products (id),
  hazard_type        text NOT NULL,
  -- The provider's own identifier: USGS event id, EMSC unid, GDACS (eventtype, eventid),
  -- ECCC GeoMet feature id `<alert-thread><YYYYMMDDhhmm>_<feature_id>` (P0 verification V1).
  primary_key        text NOT NULL,
  first_ingested_at  timestamptz NOT NULL,
  -- Set when ComCat later associates two events we had held apart. The younger record is merged
  -- into the older; its versions stay, and correlation re-runs for the survivor (§4.6).
  merged_into        bigint REFERENCES geonerva.source_records (id),
  merged_at          timestamptz,
  merge_reason       text,
  UNIQUE (source_id, primary_key),
  CHECK ((merged_into IS NULL) = (merged_at IS NULL)),
  CHECK (merged_into IS NULL OR merged_into <> id)
);

COMMENT ON TABLE geonerva.source_records IS
  'The GeoNerva identity of one provider record. Content lives in observation_versions.';

CREATE INDEX source_records_merged_into_idx
  ON geonerva.source_records (merged_into) WHERE merged_into IS NOT NULL;
CREATE INDEX source_records_source_hazard_idx
  ON geonerva.source_records (source_id, hazard_type);

CREATE TABLE geonerva.source_record_aliases (
  source_id         text NOT NULL REFERENCES geonerva.sources (id),
  alias             text NOT NULL,
  source_record_id  bigint NOT NULL REFERENCES geonerva.source_records (id),
  first_seen_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_id, alias)
);

COMMENT ON TABLE geonerva.source_record_aliases IS
  'Every identifier a provider has used for a record (USGS `ids`). Lookup by any alias is what
   makes ingestion idempotent across a preferred-id change (DOMAIN_MODEL §6.6).';

CREATE INDEX source_record_aliases_record_idx
  ON geonerva.source_record_aliases (source_record_id);

CREATE TABLE geonerva.observation_versions (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id   bigint NOT NULL REFERENCES geonerva.source_records (id),
  version_seq        integer NOT NULL CHECK (version_seq >= 1),
  -- Denormalized from source_records so that filtered spatial scans stay on one table.
  hazard_type        text NOT NULL,
  ingestion_run_id   uuid REFERENCES geonerva.ingestion_runs (id),

  -- ── Time semantics (DOMAIN_MODEL §2) ──────────────────────────────────────
  -- When GeoNerva learned it: the batch timestamp. The only thing replay filters on.
  ingested_at        timestamptz NOT NULL,
  -- When the phenomenon happened, per the provider.
  observed_at        timestamptz NOT NULL,
  -- The interval the provider says the record applies to. NULL for instantaneous events.
  valid_from         timestamptz,
  valid_to           timestamptz,
  -- When the provider says it last revised this record. NULL for FIRMS (no such time exists).
  source_updated_at  timestamptz,

  lifecycle_status   text NOT NULL CHECK (lifecycle_status IN (
                       'ACTIVE', 'UPDATED', 'ENDED', 'CANCELLED', 'EXPIRED',
                       -- The provider explicitly withdrew the record.
                       'DELETED',
                       -- Inferred: the record vanished from a source with no deletion channel
                       -- (EMSC FDSN), after two consecutive reconciles.
                       'MISSING_FROM_SOURCE')),

  -- Provider severity, preserved on its own scale and never translated (DOMAIN_MODEL §1.4).
  severity_scheme    text CHECK (severity_scheme IN
                       ('GDACS_ALERT', 'PAGER', 'ECCC_RISK_COLOUR', 'CAP_SEVERITY')),
  severity_value     text,
  -- The provider's status word, verbatim, e.g. 'reviewed'.
  provider_status    text,
  -- The agency credited with this specific solution (EMSC `auth`, USGS `net`). A column, not an
  -- attribute, because independence depends on it: EMSC republishing an NEIC solution is not a
  -- second opinion and can even carry a stale magnitude (P0: USGS M4.5 vs EMSC M3.2, Δt 0 s).
  contributor        text,

  -- Typed columns for the values the read path filters and ranks on.
  magnitude          numeric(4, 2),
  magnitude_type     text,
  depth_km           numeric(6, 2),

  -- Always present: the representative point, in geography so that distance is spheroidal.
  centroid           geography(Point, 4326) NOT NULL,
  geometry_kind      text NOT NULL CHECK (geometry_kind IN (
                       'EPICENTER', 'DETECTION_PIXEL_CENTER', 'REGION_POLYGON', 'MODEL_AREA',
                       'TRACK_OBSERVED', 'TRACK_FORECAST', 'WIND_BUFFER', 'UNCERTAINTY_CONE',
                       'CENTROID_ONLY', 'THREAT_AREA')),

  -- Hazard-specific normalized JSON, validated by a Zod schema per hazard type in packages/domain.
  attributes         jsonb NOT NULL,
  title              text,
  source_url         text,
  -- e.g. GDACS EQ: { "source": "usgs", "ref": "us7000tikb" }.
  derived_from       jsonb,
  -- Hash of the **normalized** content. The one and only change detector.
  content_sha256     bytea NOT NULL CHECK (octet_length(content_sha256) = 32),
  raw_record_id      bigint REFERENCES geonerva.raw_source_records (id),

  UNIQUE (source_record_id, version_seq),
  -- Invariant I13: a provider may be at most five minutes ahead of us.
  CHECK (observed_at <= ingested_at + interval '5 minutes'),
  CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from),
  CHECK ((severity_scheme IS NULL) = (severity_value IS NULL)),
  CHECK (jsonb_typeof(attributes) = 'object'),
  CHECK (octet_length(attributes::text) <= 16384)
);

COMMENT ON TABLE geonerva.observation_versions IS
  'Immutable versions of provider content. Never updated, never deleted except by retention.';
COMMENT ON COLUMN geonerva.observation_versions.contributor IS
  'Agency credited with this solution. Used by correlation to decide source independence.';
COMMENT ON COLUMN geonerva.observation_versions.content_sha256 IS
  'Hash of normalized content. A new version exists only where this differs from the previous
   one — never because a provider restamped its "last modified" field.';

CREATE INDEX observation_versions_centroid_gix
  ON geonerva.observation_versions USING gist (centroid);
-- The as-of lookup: "latest version of this record with ingested_at <= T".
CREATE INDEX observation_versions_record_ingested_idx
  ON geonerva.observation_versions (source_record_id, ingested_at DESC, version_seq DESC);
CREATE INDEX observation_versions_hazard_observed_idx
  ON geonerva.observation_versions (hazard_type, observed_at DESC);
CREATE INDEX observation_versions_ingested_brin_idx
  ON geonerva.observation_versions USING brin (ingested_at);
-- Baseline scans over the earthquake catalog.
CREATE INDEX observation_versions_eq_magnitude_idx
  ON geonerva.observation_versions (magnitude, observed_at DESC)
  WHERE hazard_type = 'EARTHQUAKE';
CREATE INDEX observation_versions_run_idx
  ON geonerva.observation_versions (ingestion_run_id);

CREATE TABLE geonerva.observation_geometries (
  observation_version_id  bigint NOT NULL REFERENCES geonerva.observation_versions (id) ON DELETE CASCADE,
  role                    text NOT NULL,
  seq                     smallint NOT NULL,
  -- For forecast geometry: the time this shape applies to. Forecasts are modelled here, never
  -- through a future observed_at (DOMAIN_MODEL §2).
  valid_at                timestamptz,
  is_forecast             boolean NOT NULL DEFAULT false,
  geog                    geography(Geometry, 4326) NOT NULL,
  PRIMARY KEY (observation_version_id, role, seq)
);

COMMENT ON TABLE geonerva.observation_geometries IS
  'Role-tagged geometries: affected_area, track_forecast, wind_120, cone, region, …';

CREATE INDEX observation_geometries_geog_gix
  ON geonerva.observation_geometries USING gist (geog);
-- Viewport filtering uses planar envelopes; only this index sees `geometry` (ARCHITECTURE §7.1).
CREATE INDEX observation_geometries_geom_gix
  ON geonerva.observation_geometries USING gist ((geog::geometry));

CREATE TABLE geonerva.source_record_heads (
  source_record_id     bigint PRIMARY KEY REFERENCES geonerva.source_records (id),
  latest_version_id    bigint NOT NULL REFERENCES geonerva.observation_versions (id),
  latest_version_seq   integer NOT NULL,
  latest_ingested_at   timestamptz NOT NULL,
  latest_content_sha256 bytea NOT NULL CHECK (octet_length(latest_content_sha256) = 32)
);

COMMENT ON TABLE geonerva.source_record_heads IS
  'Cache of "the latest version" for the now fast path. Maintained in the same transaction as the
   version insert, and asserted equal to the as-of path by an integration test (ARCHITECTURE §5).';

CREATE INDEX source_record_heads_ingested_idx
  ON geonerva.source_record_heads (latest_ingested_at DESC);
