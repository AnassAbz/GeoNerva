-- 0004 — canonical events, correlation links and the "now" projection cache
-- (DOMAIN_MODEL §4.8, §6.3, ADR-005).
--
-- A canonical event is **identity only**. Its values are projected from the linked records'
-- latest versions, never stored as truth. Links are bitemporal: a replay at T uses links with
-- `linked_at <= T < coalesce(unlinked_at, ∞)`, which is what lets a split or a merge be replayed
-- exactly as it was believed at the time.

CREATE TABLE geonerva.canonical_events (
  id             uuid PRIMARY KEY,
  -- User-facing identifier, e.g. EQ-26-7K3F9Q. Merged events' public ids redirect.
  public_id      text NOT NULL UNIQUE,
  hazard_type    text NOT NULL,
  created_at     timestamptz NOT NULL,
  created_by_run uuid REFERENCES geonerva.ingestion_runs (id),
  merged_into    uuid REFERENCES geonerva.canonical_events (id),
  merged_at      timestamptz,
  CHECK ((merged_into IS NULL) = (merged_at IS NULL)),
  CHECK (merged_into IS NULL OR merged_into <> id)
);

COMMENT ON TABLE geonerva.canonical_events IS
  'Identity of one real-world event across providers. Values are projected, never stored here.';

CREATE INDEX canonical_events_merged_into_idx
  ON geonerva.canonical_events (merged_into) WHERE merged_into IS NOT NULL;
CREATE INDEX canonical_events_hazard_created_idx
  ON geonerva.canonical_events (hazard_type, created_at DESC);

CREATE TABLE geonerva.canonical_links (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canonical_event_id uuid NOT NULL REFERENCES geonerva.canonical_events (id),
  source_record_id   bigint NOT NULL REFERENCES geonerva.source_records (id),
  relation           text NOT NULL CHECK (relation IN ('PRIMARY', 'SAME_EVENT', 'DERIVED_COPY')),
  match_kind         text NOT NULL CHECK (match_kind IN ('IDENTITY_REF', 'SPATIOTEMPORAL', 'SEED')),
  confidence         numeric(4, 3) CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
  -- The reason codes and measured misfits behind the decision; shown verbatim as evidence.
  reasons            jsonb,
  algorithm_version  text NOT NULL,
  linked_at          timestamptz NOT NULL,
  unlinked_at        timestamptz,
  unlink_reason      text,
  CHECK (unlinked_at IS NULL OR unlinked_at >= linked_at)
);

COMMENT ON TABLE geonerva.canonical_links IS
  'Bitemporal links from a source *record* (not a version) to a canonical event. Re-evaluation
   closes and reopens links rather than mutating them, so history survives (DOMAIN_MODEL §6.6).';

-- Invariant I6: a source record has at most one active canonical link.
CREATE UNIQUE INDEX canonical_links_one_active_idx
  ON geonerva.canonical_links (source_record_id) WHERE unlinked_at IS NULL;
CREATE INDEX canonical_links_event_active_idx
  ON geonerva.canonical_links (canonical_event_id) WHERE unlinked_at IS NULL;
CREATE INDEX canonical_links_record_linked_idx
  ON geonerva.canonical_links (source_record_id, linked_at);
-- The as-of link lookup for an event: linked_at <= T < coalesce(unlinked_at, ∞).
CREATE INDEX canonical_links_event_window_idx
  ON geonerva.canonical_links (canonical_event_id, linked_at, unlinked_at);

CREATE TABLE geonerva.correlation_candidates (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_a           bigint NOT NULL REFERENCES geonerva.source_records (id),
  record_b           bigint NOT NULL REFERENCES geonerva.source_records (id),
  decision           text NOT NULL CHECK (decision IN ('POSSIBLE_MATCH', 'NO_MATCH_CLOSE')),
  score              numeric(4, 3) CHECK (score IS NULL OR (score >= 0 AND score <= 1)),
  reasons            jsonb,
  algorithm_version  text NOT NULL,
  evaluated_at       timestamptz NOT NULL,
  superseded_at      timestamptz,
  -- Ordering the pair makes the uniqueness constraint meaningful rather than direction-dependent.
  CHECK (record_a < record_b),
  UNIQUE (record_a, record_b, algorithm_version, evaluated_at)
);

COMMENT ON TABLE geonerva.correlation_candidates IS
  'Pairs that scored close but were not merged. Shown as "possibly the same event", never merged.';

CREATE INDEX correlation_candidates_a_idx
  ON geonerva.correlation_candidates (record_a) WHERE superseded_at IS NULL;
CREATE INDEX correlation_candidates_b_idx
  ON geonerva.correlation_candidates (record_b) WHERE superseded_at IS NULL;

CREATE TABLE geonerva.canonical_event_state (
  canonical_event_id    uuid PRIMARY KEY REFERENCES geonerva.canonical_events (id),
  hazard_type           text NOT NULL,
  -- The knowledge time this projection was computed for; for the live cache, the latest batch.
  as_of                 timestamptz NOT NULL,
  engine_version        text NOT NULL,
  observed_at           timestamptz NOT NULL,
  centroid              geography(Point, 4326) NOT NULL,
  footprint             geography(Geometry, 4326),
  is_active             boolean NOT NULL,
  magnitude             numeric(4, 2),
  severity_scheme       text,
  severity_value        text,
  -- Projected headline values and agreement, already shaped for the read model.
  headline              jsonb NOT NULL,
  agreement             jsonb NOT NULL,
  n_sources             integer NOT NULL CHECK (n_sources >= 0),
  -- Excludes DERIVED_COPY links: GDACS restating USGS is not a second opinion (ADR-006).
  n_independent_sources integer NOT NULL CHECK (n_independent_sources >= 0),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  CHECK (n_independent_sources <= n_sources)
);

COMMENT ON TABLE geonerva.canonical_event_state IS
  'Rebuildable "now" projection for fast map and radius queries. Never read for a replay.';

CREATE INDEX canonical_event_state_centroid_gix
  ON geonerva.canonical_event_state USING gist (centroid);
CREATE INDEX canonical_event_state_footprint_gix
  ON geonerva.canonical_event_state USING gist (footprint);
CREATE INDEX canonical_event_state_centroid_geom_gix
  ON geonerva.canonical_event_state USING gist ((centroid::geometry));
CREATE INDEX canonical_event_state_active_idx
  ON geonerva.canonical_event_state (hazard_type, is_active, observed_at DESC);

CREATE TABLE geonerva.event_relations (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Subject references (`CE:…`, `FC:…`), so that an edge can join an event to a fire cluster.
  from_ref        text NOT NULL,
  to_ref          text NOT NULL,
  relation        text NOT NULL,
  reasons         jsonb,
  established_at  timestamptz NOT NULL,
  ended_at        timestamptz,
  CHECK (from_ref <> to_ref),
  CHECK (ended_at IS NULL OR ended_at >= established_at)
);

COMMENT ON TABLE geonerva.event_relations IS
  'RELATED edges only, never SAME: a GDACS wildfire event next to a fire cluster, a warning next
   to an event. Merging different hazard identities is deliberately impossible here.';

CREATE INDEX event_relations_from_idx ON geonerva.event_relations (from_ref) WHERE ended_at IS NULL;
CREATE INDEX event_relations_to_idx ON geonerva.event_relations (to_ref) WHERE ended_at IS NULL;
