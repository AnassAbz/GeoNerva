/**
 * The vocabulary two FDSN services already share.
 *
 * This existed inside the USGS module until EMSC arrived, which is the right moment to extract it:
 * an abstraction invented for one implementation is a guess, and the G4 review recorded it as
 * deliberately deferred until there was a second service to abstract *over*.
 *
 * What is shared is genuinely the protocol — a half-open window, the millisecond that bridges it
 * to FDSN's inclusive `endtime`, and the fact that a query is validated before it can become a
 * URL. What is **not** shared stays in each provider's own module, and that turned out to be most
 * of it: USGS refuses an over-large window with HTTP 400 and EMSC silently truncates it at 20,000
 * rows; USGS supports `includedeleted` and EMSC answers 400 for it; USGS returns 200-with-error
 * from `count` and EMSC returns a plain `{count}`. Pretending those were one behaviour is how a
 * shared base class quietly turns a loud failure into a silent one.
 */

import { z } from 'zod';

/**
 * A bounded historical question.
 *
 * `from` is inclusive and `to` is exclusive, which is *our* convention and not the service's —
 * `endtime` is inclusive there. `bridgeEndtime` subtracts a millisecond to cross between them, so
 * that adjacent windows generated by the planner cannot both claim an event on the boundary.
 */
export interface FdsnWindow {
  readonly from: Date;
  readonly to: Date;
  /** Lower magnitude bound, inclusive. Omitted means every magnitude, including nulls. */
  readonly minMagnitude?: number;
}

/** Validation for a window, so an impossible query never reaches the network. */
export const fdsnWindowSchema = z
  .object({
    from: z.date(),
    to: z.date(),
    minMagnitude: z.number().min(-2).max(12).optional(),
  })
  .refine((window) => window.from.getTime() < window.to.getTime(), {
    message: 'from must be strictly before to',
  })
  .refine((window) => Number.isFinite(window.from.getTime()), { message: 'from must be a date' })
  .refine((window) => Number.isFinite(window.to.getTime()), { message: 'to must be a date' });

/** Raised when a window is not a question an FDSN service can be asked. */
export class FdsnQueryError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'FdsnQueryError';
  }
}

export function assertWindow(window: FdsnWindow): FdsnWindow {
  const parsed = fdsnWindowSchema.safeParse(window);
  if (!parsed.success) {
    throw new FdsnQueryError(
      `invalid FDSN window: ${parsed.error.issues.map((issue) => issue.message).join('; ')}`,
    );
  }
  return window;
}

/** Ours is half-open, theirs is closed. One millisecond is the whole bridge. */
export function bridgeEndtime(to: Date): string {
  return new Date(to.getTime() - 1).toISOString();
}
