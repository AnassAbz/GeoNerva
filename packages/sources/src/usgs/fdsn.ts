/**
 * The USGS FDSN event service — the historical/query interface (DATA_SOURCES §1.1).
 *
 * This is deliberately *not* another feed. A summary feed is "whatever is current"; FDSN answers a
 * bounded question and has its own failure modes, its own limits, and its own idea of what a
 * deleted event looks like.
 *
 * Three things it does that the feed path does not:
 *
 *  - **Typed, validated parameters, never query-string passthrough.** A caller cannot smuggle an
 *    arbitrary parameter into a request this client will sign off on, and every value is bounded
 *    before it reaches a URL.
 *  - **Treats "too many results" as a planning signal, not a failure.** The service refuses more
 *    than 20,000 rows with a 400, and P0 saw an open-ended query answer **503 "table is full"**
 *    instead. Both mean the same thing operationally — split the window — so both are classified
 *    that way rather than one being a mystery.
 *  - **Knows that a deleted event may have no identity left.** See `parseDeletionSweep`.
 */

import { z } from 'zod';

import type { HttpClient, SourceFetchError } from '@geonerva/http';

import { usgsFeedSchema, type UsgsFeature } from './schema.ts';

const FDSN_HOST = 'earthquake.usgs.gov';
const FDSN_BASE = `https://${FDSN_HOST}/fdsnws/event/1`;

/** The service refuses a query matching more rows than this, and says so in the error body. */
export const FDSN_MAX_ROWS = 20_000;

/**
 * A bounded historical question.
 *
 * `from` is inclusive and `to` is exclusive, which is *our* convention and not the service's —
 * `endtime` is inclusive there. `fdsnQueryUrl` subtracts a millisecond to bridge the two, so that
 * adjacent windows generated by the planner cannot both claim an event on the boundary.
 */
export interface FdsnWindow {
  readonly from: Date;
  readonly to: Date;
  /** Lower magnitude bound, inclusive. Omitted means every magnitude, including nulls. */
  readonly minMagnitude?: number;
}

export type FdsnMode = 'live' | 'deleted-only';

/** Validation for a window, so an impossible query never reaches the network. */
export const fdsnWindowSchema = z
  .object({
    from: z.date(),
    to: z.date(),
    minMagnitude: z.number().min(-2).max(12).optional(),
  })
  .refine((window) => window.from.getTime() < window.to.getTime(), {
    message: 'from must be strictly before to',
  })
  .refine((window) => Number.isFinite(window.from.getTime()), { message: 'from must be a date' })
  .refine((window) => Number.isFinite(window.to.getTime()), { message: 'to must be a date' });

/** Raised when a window is not a question FDSN can be asked. */
export class FdsnQueryError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'FdsnQueryError';
  }
}

function assertWindow(window: FdsnWindow): FdsnWindow {
  const parsed = fdsnWindowSchema.safeParse(window);
  if (!parsed.success) {
    throw new FdsnQueryError(
      `invalid FDSN window: ${parsed.error.issues.map((issue) => issue.message).join('; ')}`,
    );
  }
  return window;
}

/**
 * Builds the query URL.
 *
 * The parameter list is closed. Adding one is a code change and a review, which is the point:
 * a passthrough would let a caller turn this into an arbitrary outbound request to a host the
 * allowlist has already approved.
 */
export function fdsnQueryUrl(window: FdsnWindow, mode: FdsnMode = 'live'): string {
  assertWindow(window);
  const params = new URLSearchParams({
    format: 'geojson',
    starttime: window.from.toISOString(),
    // Ours is half-open, theirs is closed. One millisecond is the whole bridge.
    endtime: new Date(window.to.getTime() - 1).toISOString(),
    orderby: 'time-asc',
  });
  if (window.minMagnitude !== undefined) {
    params.set('minmagnitude', String(window.minMagnitude));
  }
  if (mode === 'deleted-only') params.set('includedeleted', 'only');
  return `${FDSN_BASE}/query?${params.toString()}`;
}

/** The `count` endpoint, for deciding whether a window needs splitting before fetching it. */
export function fdsnCountUrl(window: FdsnWindow, mode: FdsnMode = 'live'): string {
  return fdsnQueryUrl(window, mode).replace('/query?', '/count?');
}

/** Host and path only, for logs. A window can be long but it is never a secret. */
export function fdsnEndpoint(mode: FdsnMode = 'live'): string {
  return `${FDSN_HOST}/fdsnws/event/1/${mode === 'deleted-only' ? 'query(includedeleted)' : 'query'}`;
}

const fdsnCountSchema = z.looseObject({
  count: z.number().int().min(0),
  maxAllowed: z.number().int().min(1).optional(),
  error: z.string().optional(),
});

export interface FdsnCount {
  readonly count: number;
  /** The service's own limit when it volunteers one, else the documented default. */
  readonly maxAllowed: number;
  /** True when this window cannot be fetched as one request. */
  readonly overLimit: boolean;
}

/**
 * Reads the `count` answer.
 *
 * P0 captured the case that matters: when the window is over the limit the endpoint answers
 * **HTTP 200** with `{count, maxAllowed, error}`. A client that only checked the status code would
 * read that as a successful count and then fail the real query — so the `error` field and the
 * count itself are both consulted.
 */
export function parseFdsnCount(body: Uint8Array): FdsnCount {
  let json: unknown;
  try {
    json = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(body));
  } catch {
    throw new FdsnQueryError('the FDSN count endpoint did not answer with JSON');
  }
  const parsed = fdsnCountSchema.safeParse(json);
  if (!parsed.success) {
    throw new FdsnQueryError(
      `the FDSN count answer changed shape: ${parsed.error.issues
        .map((issue) => `${issue.path.map(String).join('.') || '(root)'}: ${issue.message}`)
        .join('; ')}`,
    );
  }
  const maxAllowed = parsed.data.maxAllowed ?? FDSN_MAX_ROWS;
  return {
    count: parsed.data.count,
    maxAllowed,
    overLimit: parsed.data.error !== undefined || parsed.data.count > maxAllowed,
  };
}

/**
 * Whether a failed FDSN request is really "this window is too big".
 *
 * The 400 says so in words. The 503 does not — P0 saw `table is full` from an open-ended query
 * from 2000-01-01 — but it means the same thing to a caller holding a splittable window, and
 * treating it as an ordinary server error would retry the same impossible query three times and
 * then abandon the backfill.
 */
export function isWindowTooLarge(error: SourceFetchError, bodyText?: string): boolean {
  const status = error.context.status;
  if (status !== 400 && status !== 503) return false;

  if (bodyText === undefined) {
    /*
     * The hardened client discards a non-2xx body rather than risk putting provider bytes into an
     * error, so at the call site the words are usually gone.
     *
     * A **400** is still safe to read as "too many rows": the parameters are typed, validated and
     * closed, so a caller cannot produce a malformed FDSN query, and a 400 on a window that
     * passed the count check is a disagreement about size.
     *
     * A **503** is not. P0 did see `table is full` arrive as one, but 503 is also the ordinary
     * "the provider is busy", and splitting on it would halve a healthy window permanently — the
     * parent stays SPLIT, so a transient outage leaves a distortion that resuming never repairs.
     * Without the body to tell them apart, a 503 goes to the ordinary retry path.
     */
    return status === 400;
  }

  const text = bodyText.toLowerCase();
  if (status === 400) {
    // With the body in hand, be exact: a 400 for any other reason is a bug in our parameters.
    return text.includes('exceeds search limit') || text.includes('modify the search');
  }
  return text.includes('table is full');
}

/** A deleted event that still carries enough identity to tombstone the right record. */
export interface IdentifiedDeletion {
  readonly primaryKey: string;
  readonly aliases: readonly string[];
  readonly observedAt: Date;
  readonly sourceUpdatedAt: Date | null;
}

export interface DeletionSweep {
  readonly deletions: readonly IdentifiedDeletion[];
  /**
   * Deleted entries USGS has stripped of all identity.
   *
   * Real and common: of 98 deletions in the P0 capture, **55 had an empty `id` and null `ids`,
   * `net` and `code`**. A purged event keeps its time and geometry and nothing else. There is no
   * way to know which record it was, so these are counted and reported — never silently dropped,
   * and never guessed at.
   */
  readonly unidentifiable: number;
}

/**
 * A deletion-tolerant feature. `id` may be empty and `ids` may be null, which the live schema
 * rightly refuses; here it is the normal case for a purged event.
 */
const deletedFeatureSchema = z.looseObject({
  type: z.literal('Feature'),
  id: z.string(),
  properties: z.looseObject({
    time: z.number(),
    updated: z.number().nullable(),
    ids: z.string().nullable(),
    status: z.string(),
  }),
});

/**
 * Parses an `includedeleted=only` answer into tombstone instructions.
 *
 * The batch verdict is deliberately *not* applied to the identity-less fraction. A majority of
 * purged deletions having no identity is documented provider behaviour, not drift, and running it
 * past a 20 % reject threshold would fail every sweep. What *is* suspicious is a non-empty sweep
 * in which **nothing** is identifiable: that would mean we are blind to every deletion, and it is
 * reported as drift.
 */
export function parseDeletionSweep(body: Uint8Array): DeletionSweep {
  let json: unknown;
  try {
    json = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(body));
  } catch {
    throw new FdsnQueryError('the FDSN deletion sweep did not answer with JSON');
  }

  const envelope = usgsFeedSchema.safeParse(json);
  if (!envelope.success) {
    throw new FdsnQueryError(
      `the FDSN deletion sweep changed shape: ${envelope.error.issues
        .map((issue) => `${issue.path.map(String).join('.') || '(root)'}: ${issue.message}`)
        .join('; ')}`,
    );
  }

  const deletions: IdentifiedDeletion[] = [];
  let unidentifiable = 0;

  for (const candidate of envelope.data.features) {
    const parsed = deletedFeatureSchema.safeParse(candidate);
    if (!parsed.success) {
      // Not even the deletion-tolerant shape. That is drift in the sweep itself.
      throw new FdsnQueryError(
        `a deletion entry did not match even the tolerant shape: ${parsed.error.issues
          .map((issue) => issue.message)
          .join('; ')}`,
      );
    }
    const feature = parsed.data;

    /*
     * Assert the entry really is a deletion.
     *
     * Everything here becomes a tombstone instruction, so the whole sweep rests on
     * `includedeleted=only` having been honoured. If that parameter were ever ignored, renamed,
     * cached or served stale, a body of *live* earthquakes would mass-tombstone every record it
     * touched — every affected head would read "no longer stands", which is the false "nothing
     * here" this project treats as its worst failure. USGS sends the discriminator on every
     * feature, so checking it costs nothing.
     */
    if (feature.properties.status !== 'deleted') {
      throw new FdsnQueryError(
        `the deletion sweep returned a feature with status "${feature.properties.status}"; ` +
          'refusing to tombstone records from a body that is not a deletion list',
      );
    }

    const aliases = aliasesOf(feature.properties.ids, feature.id);
    // The first alias doubles as the identity check: no alias means USGS stripped this entry.
    const fallbackKey = aliases[0];
    if (fallbackKey === undefined) {
      unidentifiable += 1;
      continue;
    }
    const primaryKey = feature.id.length > 0 ? feature.id : fallbackKey;
    deletions.push({
      primaryKey,
      aliases,
      observedAt: new Date(feature.properties.time),
      sourceUpdatedAt:
        feature.properties.updated === null ? null : new Date(feature.properties.updated),
    });
  }

  if (envelope.data.features.length > 0 && deletions.length === 0) {
    throw new FdsnQueryError(
      `all ${envelope.data.features.length} deletions in this sweep are unidentifiable; ` +
        'a sweep that can tombstone nothing means GeoNerva is blind to deletions',
    );
  }

  return { deletions, unidentifiable };
}

function aliasesOf(ids: string | null, id: string): readonly string[] {
  const set = new Set<string>();
  for (const part of (ids ?? '').split(',')) {
    const trimmed = part.trim();
    if (trimmed.length > 0) set.add(trimmed);
  }
  if (id.length > 0) set.add(id);
  return [...set].sort();
}

export interface FdsnFetchOptions {
  readonly client: HttpClient;
  readonly signal?: AbortSignal;
}

export interface FdsnBody {
  readonly body: Uint8Array;
  readonly httpStatus: number;
  readonly bytes: number;
  readonly attempts: number;
  readonly durationMs: number;
}

/** Counts a window, so the planner can decide whether to split before paying for the rows. */
export async function fdsnCount(
  window: FdsnWindow,
  mode: FdsnMode,
  options: FdsnFetchOptions,
): Promise<FdsnCount> {
  const response = await options.client.get(fdsnCountUrl(window, mode), {
    ...(options.signal === undefined ? {} : { signal: options.signal }),
  });
  return parseFdsnCount(response.body);
}

/** Fetches one window. Throws `SourceFetchError`; the caller decides whether to split. */
export async function fdsnFetch(
  window: FdsnWindow,
  mode: FdsnMode,
  options: FdsnFetchOptions,
): Promise<FdsnBody> {
  const response = await options.client.get(fdsnQueryUrl(window, mode), {
    ...(options.signal === undefined ? {} : { signal: options.signal }),
  });
  return {
    body: response.body,
    httpStatus: response.status,
    bytes: response.bytes,
    attempts: response.attempts,
    durationMs: response.durationMs,
  };
}

